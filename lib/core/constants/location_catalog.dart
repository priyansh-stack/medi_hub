  /// Returns sorted list of supported countries.
  static List<String> get countries => _data.keys.toList();

  /// Returns registered states for given country.
  static List<String> getStatesForCountry(String country) {
    return _data[country] ?? const [];
  }

  /// Checks if country is valid.
  static bool isValidCountry(String? country) {
    if (country == null) return false;
    return _data.containsKey(country);
  }

  /// Checks if state is valid for given country.
  static bool isValidState(String? country, String? state) {
    if (country == null || state == null) return false;
    final states = _data[country];
    if (states == null) return false;
    return states.contains(state);
  }
